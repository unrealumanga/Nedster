"""Session title text rules shared by the store, the CLI and the TUI.

Titles are never generated by a model: an empty title is filled locally from the first
user message. Everything here is pure text so every surface shows the same name.
"""

from __future__ import annotations

import re
import time
from datetime import datetime

#: Longest stored/displayed title, ellipsis included.
TITLE_LIMIT = 80

#: Shown when a session has neither an explicit name nor a usable first message.
UNTITLED = "Untitled conversation"

#: C0/C1 control characters (kept out of the terminal); tab/CR/LF are handled as whitespace.
_CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f]")


def normalize_title(text: str, *, limit: int = TITLE_LIMIT) -> str:
    """First non-empty line of ``text``, whitespace collapsed, control characters dropped.

    Longer than ``limit`` is cut at a word boundary and marked with ``…``, so the result
    is never longer than ``limit``. Returns ``""`` when nothing usable remains.
    """
    if not text:
        return ""
    for line in re.split(r"[\r\n]", str(text)):
        collapsed = " ".join(_CONTROL_RE.sub("", line).split())
        if collapsed:
            break
    else:
        return ""
    if len(collapsed) <= limit:
        return collapsed
    head = collapsed[: limit - 1].rstrip()
    if " " in head:
        head = head.rsplit(" ", 1)[0].rstrip()
    if not head:
        head = collapsed[: limit - 1]
    return head + "…"


def display_title(title: str, first_user_text: str = "") -> str:
    """Title for display: the name when set, else the first message, else ``UNTITLED``."""
    name = (title or "").strip()
    return name or normalize_title(first_user_text) or UNTITLED


def relative_age(ns: int, now: float | None = None) -> str:
    """Compact age for a listing: "just now", "5m ago", "yesterday", a date when older than a week."""
    if not ns:
        return ""
    seconds = max(0.0, (time.time() if now is None else now) - int(ns) / 1e9)
    if seconds < 90:
        return "just now"
    if seconds < 3600:
        return f"{int(seconds // 60)}m ago"
    if seconds < 86_400:
        return f"{int(seconds // 3600)}h ago"
    if seconds < 172_800:
        return "yesterday"
    if seconds < 7 * 86_400:
        return f"{int(seconds // 86_400)}d ago"
    return datetime.fromtimestamp(int(ns) / 1e9).strftime("%Y-%m-%d")
